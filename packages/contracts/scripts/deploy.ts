import { ethers, artifacts, network } from "hardhat";
import * as fs from "fs";
import * as path from "path";

const OUTPUT_FILE = path.resolve(__dirname, "../../frontend/src/contracts/deployedContract.ts");

async function main() {
  const [deployer] = await ethers.getSigners();
  if (!deployer) {
    throw new Error("No account found. Set PRIVATE_KEY in packages/contracts/.env");
  }
  console.log(`Network: ${network.name} | Deployer: ${deployer.address}`);

  const factory = await ethers.getContractFactory("AgroLogNASA");
  const contract = await factory.deploy();
  await contract.waitForDeployment();
  const address = await contract.getAddress();
  console.log(`AgroLogNASA deployed at: ${address}`);

  // Export address + ABI to the frontend.
  const { abi } = await artifacts.readArtifact("AgroLogNASA");
  const source = `// AUTO-GENERATED by packages/contracts/scripts/deploy.ts - do not edit by hand.
import type { Address } from "viem";

export const CONTRACT_ADDRESS: Address = "${address}";

export const CONTRACT_ABI = ${JSON.stringify(abi, null, 2)} as const;
`;
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, source);
  console.log(`Frontend config updated: ${OUTPUT_FILE}`);
  console.log(`Snowtrace: https://testnet.snowtrace.io/address/${address}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
